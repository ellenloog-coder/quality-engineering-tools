      const titleEnglish = "Quality Tools — Homepage Demo";
      const switchButton = document.getElementById("languageBtn");
      const translatableNodes = [];

      const walker = document.createTreeWalker(
        document.body,
        NodeFilter.SHOW_TEXT,
        {
          acceptNode(node) {
            const parent = node.parentElement;
            if (!parent || ["SCRIPT", "STYLE", "NOSCRIPT"].includes(parent.tagName)) {
              return NodeFilter.FILTER_REJECT;
            }
            const normalized = node.nodeValue.replace(/\s+/g, " ").trim();
            return normalized ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
          }
        }
      );

